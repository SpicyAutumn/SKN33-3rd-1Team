# 긴 이름이 먼저 걸리도록 정렬한다(`서귀포`가 `서`보다 먼저).
_CITY_PATTERN = re.compile(r"^(" + "|".join(sorted(CITIES, key=len, reverse=True)) + r")")
_ADDRESS_PATTERN = re.compile(
    r"(" + "|".join(sorted(PROVINCES, key=len, reverse=True)) + r")\s*([가-힣]{2,5}(?:시|군|구))?"
)


def from_title(title: str) -> str | None:
    """`강릉 오죽헌`, `강릉향교`처럼 제목 앞머리에 붙은 지역명을 찾는다."""
    match = _CITY_PATTERN.match((title or "").strip())
    return match.group(1) if match else None


def from_content(content: str) -> str | None:
    """본문의 `경상북도 경주시` 같은 행정구역 표기를 찾는다."""
    match = _ADDRESS_PATTERN.search(content or "")
    if not match:
        return None
    province, city = match.group(1), match.group(2)
    return f"{province} {city}" if city else province


def detect(title: str, content: str) -> tuple[str, str] | None:
    """(지역명, 근거) 를 돌려준다. 제목을 먼저 보고 없으면 본문을 본다."""
    city = from_title(title)
    if city:
        return city, "제목"
    place = from_content(content)
    if place:
        return place, "본문"
    return None
